fn decision_color(category: DecisionCategory) -> Hsla {
    match category {
        DecisionCategory::Money | DecisionCategory::Security => tokens::closed(),
        DecisionCategory::Data | DecisionCategory::EventFormat | DecisionCategory::Api => {
            tokens::pending()
        }
        DecisionCategory::Behavior | DecisionCategory::Other => tokens::link(),
    }
}

pub fn to_github_side(side: SnippetSide) -> Side {
    match side {
        SnippetSide::New => Side::Right,
        SnippetSide::Old => Side::Left,
    }
}

fn strip_diff_prefix(raw: &str) -> (char, &str) {
    if let Some(rest) = raw.strip_prefix('+') {
        ('+', rest)
    } else if let Some(rest) = raw.strip_prefix('-') {
        ('-', rest)
    } else if let Some(rest) = raw.strip_prefix(' ') {
        (' ', rest)
    } else {
        (' ', raw)
    }
}

fn render_diff_line(
    raw: &str,
    runs: Vec<(std::ops::Range<usize>, HighlightStyle)>,
    muted: Hsla,
) -> AnyElement {
    let (sign, code) = strip_diff_prefix(raw);
    let (bg, sign_color) = match sign {
        '+' => (Some(tokens::diff_added_bg()), tokens::diff_added_text()),
        '-' => (Some(tokens::diff_removed_bg()), tokens::diff_removed_text()),
        _ => (None, muted),
    };
    let text: AnyElement = if code.is_empty() {
        div().child(" ").into_any_element()
    } else if runs.is_empty() {
        div().child(code.to_owned()).into_any_element()
    } else {
        StyledText::new(code.to_owned())
            .with_highlights(runs)
            .into_any_element()
    };
    h_flex()
        .w_full()
        .px_2()
        .gap_2()
        .items_start()
        .when_some(bg, |row, bg| row.bg(bg))
        .child(
            div()
                .flex_none()
                .w(dp(12.))
                .text_color(sign_color)
                .child(sign.to_string()),
        )
        .child(div().flex_1().min_w_0().child(text))
        .into_any_element()
}

/// Where `target`'s viewed marks are kept. A stack chapter's are apart from
/// the pull request's own guide: the two guides choose their step IDs apart.
fn read_state_key(cx: &App, target: &ReadTarget) -> String {
    let kind = if target.chapter {
        "guide-stack-read"
    } else {
        "guide-read"
    };
    let resource = format!("{kind}/{}/{}", target.pr.url(), target.head_oid);
    crate::cache::github_key(cx, &resource).unwrap_or_else(|| format!("local/{resource}"))
}

fn load_read_state(cx: &App, target: &ReadTarget) -> GuideReadState {
    crate::cache::get::<GuideReadState>(&read_state_key(cx, target)).unwrap_or_default()
}

fn save_read_state(cx: &App, target: &ReadTarget, state: &GuideReadState) {
    crate::cache::put(&read_state_key(cx, target), state);
}

