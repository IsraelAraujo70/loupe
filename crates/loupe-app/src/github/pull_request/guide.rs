impl Render for GuideTab {
    fn render(&mut self, window: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        if std::mem::take(&mut self.clear_review_body) {
            self.review_body
                .update(cx, |state, cx| state.set_value("", window, cx));
        }
        match &self.state {
            GuideViewState::Empty => self.render_empty(cx),
            GuideViewState::Unavailable { reason } => self.render_unavailable(reason, cx),
            GuideViewState::Generating { status, started_at } => {
                self.render_generating(status, *started_at, cx)
            }
            GuideViewState::Invalid { message } => self.render_invalid(message, cx),
            GuideViewState::Ready {
                stored,
                changed_steps,
            } => self.render_ready(stored, changed_steps, cx),
            GuideViewState::StackReady {
                stored,
                changes,
                nodes,
            } => self.render_stack_ready(stored, changes, nodes, cx),
        }
    }
}

